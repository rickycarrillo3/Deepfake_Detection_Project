"""R50-ND adapter — implements the model contract (see baselines/README.md):
    load()               -> load weights, prepare for inference
    predict(image_path)  -> float in [0, 1], predicted fake-probability

The no-downsample ResNet-50 of Corvi et al., ICASSP 2023 ("On the Detection of
Synthetic Images Generated by Diffusion Models"), retrained on TrueFake. The
paper calls it R50-ND; the checkpoint directory is R50_nodown as uploaded.

The architecture comes from the vendored grip-unina clone rather than being
retranscribed here — `resnet50(num_classes=1, stride0=1, dropout=0.5)`, the
exact factory call their own `create_architecture("res50nodown")` makes.
stride0=1 removes the stride from *both* the 7x7 stem conv and the following
maxpool, which is what preserves the low-level synthesis traces the method
depends on.

Relationship to models/
-----------------------
This is the same architecture family as models/DMimageDetection/ (DMimageDetection_GAN / DMimageDetection_DM),
but a **different checkpoint**: those are the original authors' weights, this
one was retrained by the TrueFake authors on StyleGAN2 + SDXL. Scores are not
interchangeable, which is why the results filename carries the tf- prefix.

Preprocessing
-------------
The checkpoint carries the grip-unina trainer's own format ('model' /
'optimizer' / 'total_steps'), confirming it was trained with that pipeline
rather than the TrueFake repo's. Both agree on the test-time transform anyway:
ToTensor + ImageNet normalization at native resolution, no resize or crop
(their config for Corvi2023 sets patch_size: null, norm_type: resnet).
"""

import os
import sys

import torch
import torchvision.transforms as transforms
from PIL import Image, ImageFile

ImageFile.LOAD_TRUNCATED_IMAGES = True

_MODEL_DIR = os.path.dirname(os.path.abspath(__file__))
_CLONE_DIR = os.path.join(_MODEL_DIR, "ClipBased-SyntheticImageDetection")
if _CLONE_DIR not in sys.path:
    sys.path.insert(0, _CLONE_DIR)

WEIGHTS_PATH = os.path.join(_MODEL_DIR, "best.pt")
DEVICE = "cuda:0" if torch.cuda.is_available() else "cpu"

_model = None
_transform = None


def load(**kwargs):
    """Load the R50-ND checkpoint and prepare it for inference."""
    global _model, _transform

    from networks.resnet_mod import resnet50

    model = resnet50(num_classes=1, stride0=1, dropout=0.5)
    checkpoint = torch.load(WEIGHTS_PATH, map_location="cpu")
    # grip-unina trainer format; fall back to a bare state_dict.
    state_dict = checkpoint.get("model", checkpoint)
    model.load_state_dict(state_dict, strict=True)
    _model = model.to(DEVICE).eval()

    _transform = transforms.Compose(
        [
            transforms.ToTensor(),
            transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
        ]
    )
    return _model


def predict(image_path: str) -> float:
    """Return predicted fake-probability in [0, 1] for a single image."""
    if _model is None or _transform is None:
        raise RuntimeError("model.load() must be called before predict().")

    image = Image.open(image_path).convert("RGB")
    tensor = _transform(image).unsqueeze(0).to(DEVICE)

    with torch.no_grad():
        logit = _model(tensor).flatten()[0]

    return float(torch.sigmoid(logit))


def result_stem():
    """See run.py. Trained on StyleGAN2 + SDXL fakes, so family GANDM."""
    return "tf-r50nd_GANDM"
